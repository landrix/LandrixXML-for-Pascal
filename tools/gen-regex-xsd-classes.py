#!/usr/bin/env python3
"""Generate the character classes of XML Schema patterns as the Java
runtime's Xerces (the engine of the KoSIT validator) has them.

Xerces departs from the Unicode tables the XPath modes take from Saxon
(Unicode 6.2.0, source/LandrixXmlUnicodeData.inc):

  \\p{..}  the general categories of the Java runtime (Unicode 15.0.0 for
          Java 21), for the Basic Multilingual Plane only: a character
          above U+FFFF is in no category but Cn (and in \\p{Cn} only, not
          in \\p{C})
  \\d      the decimal digits (Nd) of Unicode 3.1.0, in all planes

Two modes, which can be combined:

  python tools/gen-regex-xsd-classes.py --ucd15 UnicodeData-15.0.0.txt --ucd31 UnicodeData-3.1.0.txt
      writes source/LandrixXmlXsdClassData.inc from the two files (verified
      by their SHA-256):
        curl -o UnicodeData-15.0.0.txt https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt
        curl -o UnicodeData-3.1.0.txt https://www.unicode.org/Public/3.1-Update/UnicodeData-3.1.0.txt

  python tools/gen-regex-xsd-classes.py --java PATH/java.exe --javac PATH/javac.exe
      asks Xerces (tools/XercesRegexOracle.java) which code points the
      class escapes and categories match and writes them to
      tests/data/regex/xsd-classes.txt (pattern TAB hex ranges lo-hi ...),
      against which the unit tests check the XSD mode. Note the Java
      version in the commit: another one may have other tables.

Both files are committed; rerun this script with a new Java runtime (see
tools/check-xerces-drift.py) or to change the format.
"""

import argparse
import hashlib
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_INC = os.path.join(ROOT, "source", "LandrixXmlXsdClassData.inc")
OUT_DATA = os.path.join(ROOT, "tests", "data", "regex", "xsd-classes.txt")
SHA15 = "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73"
SHA31 = "8e57884da0da3a66782b8a6332a601fccbcae9ed0060e12501aca02fa56ffecd"
BS = chr(92)

# Order defines the ordinal values of TLandrixXmlUnicodeCategory (as in
# tools/gen-unicode-tables.py).
CATEGORIES = ["Cn", "Cc", "Cf", "Co", "Cs", "Ll", "Lm", "Lo", "Lt", "Lu", "Mc", "Me", "Mn",
              "Nd", "Nl", "No", "Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps", "Sc", "Sk", "Sm",
              "So", "Zl", "Zp", "Zs"]

# the patterns of the test data; \P{..} and the upper-case escapes are
# checked by the tests as complements
PATTERNS = ["."] + [BS + c for c in "dswic"] + [BS + "p{%s}" % c for c in CATEGORIES + list("LMNPSZC")]

HEADER = """{ LandrixXml - dependency-free XML library for Delphi and Free Pascal.

  Copyright (c) 2026 Landrix Software
  Licensed under the MIT License. See the LICENSE file in the project root
  or https://opensource.org/licenses/MIT for the full license text.

  GENERATED by tools/gen-regex-xsd-classes.py - do not edit.

  The character classes of XML Schema patterns as the Java runtime's
  Xerces has them: the general categories of Unicode 15.0.0 for the Basic
  Multilingual Plane (ranges sorted by code point; code points not
  covered are unassigned, Cn), and the decimal digits (Nd) of Unicode
  3.1.0. Derived from UnicodeData.txt 15.0.0 and 3.1.0, Copyright (c)
  Unicode, Inc., distributed under the Unicode terms of use
  (https://www.unicode.org/copyright.html). }
"""


def load(path, sha):
    data = open(path, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != sha:
        sys.exit("unexpected SHA-256 %s for %s" % (digest, path))
    cats = ["Cn"] * 0x110000
    first = None
    for line in data.decode("ascii").splitlines():
        fields = line.split(";")
        cp, name, cat = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cp
            continue
        if name.endswith(", Last>"):
            for c in range(first, cp + 1):
                cats[c] = cat
            continue
        cats[cp] = cat
    return cats


def ranges_of(pred, limit):
    out, start = [], None
    for c in range(limit + 1):
        m = c < limit and pred(c)
        if m and start is None:
            start = c
        elif not m and start is not None:
            out.append((start, c - 1))
            start = None
    return out


def wrap(values, per):
    lines = []
    for i in range(0, len(values), per):
        lines.append("    " + ", ".join(values[i:i + per]) + ("," if i + per < len(values) else ""))
    return lines


def write_inc(ucd15, ucd31):
    c15 = load(ucd15, SHA15)
    c31 = load(ucd31, SHA31)
    ranges = []
    start = 0
    for c in range(1, 0x10001):
        if c == 0x10000 or c15[c] != c15[start]:
            if c15[start] != "Cn":
                ranges.append((start, c - 1, CATEGORIES.index(c15[start])))
            start = c
    digits = ranges_of(lambda c: c31[c] == "Nd", 0x110000)
    lines = [HEADER, "const"]
    lines.append("  XsdCategoryCount = %d;" % len(ranges))
    for name, idx in (("XsdCategoryLo", 0), ("XsdCategoryHi", 1)):
        lines.append("  %s: array[0..XsdCategoryCount - 1] of Integer = (" % name)
        lines += wrap(["$%X" % r[idx] for r in ranges], 10)
        lines.append("  );")
    lines.append("  XsdCategoryOf: array[0..XsdCategoryCount - 1] of Byte = (")
    lines += wrap([str(r[2]) for r in ranges], 25)
    lines.append("  );")
    lines.append("  XsdDigitCount = %d;" % len(digits))
    lines.append("  XsdDigitRanges: array[0..XsdDigitCount * 2 - 1] of Integer = (")
    lines += wrap(["$%X, $%X" % d for d in digits], 6)
    lines.append("  );")
    with open(OUT_INC, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d category ranges, %d digit ranges written to %s" % (len(ranges), len(digits), OUT_INC))


def write_data(java, javac):
    export = "java.xml/com.sun.org.apache.xerces.internal.impl.xpath.regex=ALL-UNNAMED"
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([javac, "--add-exports", export, "-d", tmp,
                        os.path.join(ROOT, "tools", "XercesRegexOracle.java")], check=True)
        out = subprocess.run([java, "--add-exports", export, "-cp", tmp, "XercesRegexOracle"],
                             input="".join("ranges\t%s\n" % p for p in PATTERNS), check=True,
                             capture_output=True, encoding="utf-8").stdout.split("\n")
        version = subprocess.run([java, "-version"], capture_output=True, encoding="utf-8").stderr.split("\n")[0]
    lines = []
    for p, r in zip(PATTERNS, out):
        if r == "E":
            sys.exit("Xerces rejects " + p)
        lines.append(p + "\t" + r)
    with open(OUT_DATA, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d classes from %s written to %s" % (len(lines), version, OUT_DATA))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd15")
    ap.add_argument("--ucd31")
    ap.add_argument("--java")
    ap.add_argument("--javac")
    a = ap.parse_args()
    if not (a.ucd15 and a.ucd31) and not (a.java and a.javac):
        sys.exit(__doc__)
    if a.ucd15 and a.ucd31:
        write_inc(a.ucd15, a.ucd31)
    if a.java and a.javac:
        write_data(a.java, a.javac)


if __name__ == "__main__":
    main()
