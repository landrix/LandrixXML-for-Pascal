#!/usr/bin/env python3
"""Generate source/LandrixXmlCaseData.inc: the case mappings of fn:upper-case and
fn:lower-case as Saxon HE applies them, asked from Saxon itself for every XML
character (Saxon's own tables, which differ from the Java runtime's for the
letters of newer Unicode versions), including the mappings that change the
length (U+00DF -> "SS", U+FB01 -> "FI").

  python tools/gen-xpath-case-tables.py --java PATH/java.exe --saxon validator-1.6.3-standalone.jar

The jar is the KoSIT validator, which contains Saxon HE.
"""

import argparse
import os
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "source", "LandrixXmlCaseData.inc")

QUERY = """string-join(
  for $cp in (9, 10, 13, 32 to 55295, 57344 to 65533, 65536 to 1114111)
  let $s := codepoints-to-string($cp)
  let $u := upper-case($s)
  let $l := lower-case($s)
  return (
    if ($u ne $s) then concat('U ', $cp, ' ', string-join(for $c in string-to-codepoints($u) return string($c), ' ')) else (),
    if ($l ne $s) then concat('L ', $cp, ' ', string-join(for $c in string-to-codepoints($l) return string($c), ' ')) else ()),
  '&#10;')"""


def utf8_bytes(cps):
    return "".join(chr(c) for c in cps).encode("utf-8")


def pascal_table(name, entries):
    """entries: sorted list of (code point, target code points)."""
    keys = [cp for cp, _ in entries]
    pool = bytearray()
    starts = []
    for _, t in entries:
        starts.append(len(pool))
        pool += utf8_bytes(t)
    starts.append(len(pool))
    out = []
    out.append("  %sCount = %d;\n" % (name, len(keys)))
    out.append("  %sKeys: array[0..%d] of Integer = (\n" % (name, len(keys) - 1))
    out.append(wrap(["$%X" % k for k in keys]))
    out.append("  );\n")
    out.append("  { start of each target in %sPool (0-based), one more entry for the end }\n" % name)
    out.append("  %sStarts: array[0..%d] of Integer = (\n" % (name, len(starts) - 1))
    out.append(wrap([str(s) for s in starts]))
    out.append("  );\n")
    out.append("  %sPool: array[0..%d] of Byte = (\n" % (name, len(pool) - 1))
    out.append(wrap(["$%02X" % b for b in pool]))
    out.append("  );\n")
    return "".join(out)


def wrap(items):
    lines = []
    line = "   "
    for i, it in enumerate(items):
        piece = " " + it + ("," if i < len(items) - 1 else "")
        if len(line) + len(piece) > 100:
            lines.append(line)
            line = "   "
        line += piece
    lines.append(line)
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--java", required=True)
    ap.add_argument("--saxon", required=True)
    args = ap.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        q = os.path.join(tmp, "case.xq")
        with open(q, "w", encoding="ascii") as f:
            f.write(QUERY)
        out = subprocess.run([args.java, "-cp", args.saxon, "net.sf.saxon.Query", "-q:" + q, "!method=text"],
                             check=True, capture_output=True, encoding="ascii").stdout
        ver = subprocess.run([args.java, "-cp", args.saxon, "net.sf.saxon.Query", "-qs:1", "-t"],
                             capture_output=True, encoding="utf-8", errors="replace").stderr
    version = "Saxon"
    for line in ver.splitlines():
        if line.startswith("Saxon"):
            version = line.split(" from ")[0].strip()
            break
    upper, lower = [], []
    for l in out.splitlines():
        parts = l.split()
        if not parts:
            continue
        cp = int(parts[1])
        target = [int(p) for p in parts[2:]]
        (upper if parts[0] == "U" else lower).append((cp, target))
    with open(OUT, "w", encoding="ascii", newline="\r\n") as f:
        f.write("{ Generated by tools/gen-xpath-case-tables.py from %s\n"
                "  (fn:upper-case and fn:lower-case per XML character); do not edit.\n"
                "  Code points sorted ascending; the target of entry I is the UTF-8 in\n"
                "  Pool[Starts[I]] .. Pool[Starts[I + 1] - 1]. }\n\n" % version)
        f.write("const\n")
        f.write(pascal_table("UpperCase", upper))
        f.write("\n")
        f.write(pascal_table("LowerCase", lower))
    print("%s: %d upper, %d lower (%s)" % (OUT, len(upper), len(lower), version))


if __name__ == "__main__":
    main()
