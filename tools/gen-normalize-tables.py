#!/usr/bin/env python3
"""Generate source/LandrixXmlNormalizeData.inc: the Unicode normalization
data (NFC, NFD, NFKC, NFKD) of Unicode 15.0.0.

Unicode 15.0.0 is the version of java.text.Normalizer in JDK 21, which
Saxon HE 12 calls for fn:normalize-unicode (the KoSIT validator runs on
JDK 21). The regular expression categories (LandrixXmlUnicodeData.inc)
stay at 6.2.0 on purpose: that is Saxon's own regex table.

Both files are downloaded once into a folder of your choice and verified
by their SHA-256:

  curl -O https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt
  curl -O https://www.unicode.org/Public/15.0.0/ucd/DerivedNormalizationProps.txt
  python tools/gen-normalize-tables.py UnicodeData.txt DerivedNormalizationProps.txt

Output:
- the full (recursive) canonical and compatibility decomposition of every
  decomposable code point except the Hangul syllables (algorithmic), as
  offsets into one shared code point pool (the two differ for U+1E9B);
- the canonical combining classes as ranges;
- the primary composites: pairs of the direct canonical mappings of two
  code points, without Full_Composition_Exclusion, sorted by first and
  second code point;
- the quick check properties NFD_QC, NFC_QC, NFKD_QC, NFKC_QC as ranges
  of flags. They are also recomputed from the other tables and must
  agree.

The generated file is committed; rerun this script only to change the
format.
"""

import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "source", "LandrixXmlNormalizeData.inc")
SHA256_DATA = "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73"
SHA256_PROPS = "d5687a48c95c7d6e1ec59cb29c0f2e8b052018eb069a4371b7368d0561e12a29"

S_BASE, L_BASE, V_BASE, T_BASE = 0xAC00, 0x1100, 0x1161, 0x11A7
L_COUNT, V_COUNT, T_COUNT = 19, 21, 28
S_COUNT = L_COUNT * V_COUNT * T_COUNT

# quick check flags, same values as in LandrixXmlNormalize.pas
NFD_NO, NFC_NO, NFC_MAYBE, NFKD_NO, NFKC_NO, NFKC_MAYBE = 1, 2, 4, 8, 16, 32

HEADER = """{ LandrixXml - dependency-free XML library for Delphi and Free Pascal.

  Copyright (c) 2026 Landrix Software
  Licensed under the MIT License. See the LICENSE file in the project root
  or https://opensource.org/licenses/MIT for the full license text.

  GENERATED by tools/gen-normalize-tables.py - do not edit.

  Unicode normalization data, version 15.0.0 (the version of JDK 21's
  java.text.Normalizer, which Saxon HE 12 uses). Derived from
  UnicodeData.txt and DerivedNormalizationProps.txt, Copyright (c)
  1991-2022 Unicode, Inc., distributed under the Unicode terms of use
  (https://www.unicode.org/copyright.html). }
"""


def read_checked(path, digest):
    with open(path, "rb") as f:
        data = f.read()
    actual = hashlib.sha256(data).hexdigest()
    if actual != digest:
        sys.exit("%s has SHA-256 %s, expected %s" % (path, actual, digest))
    return data.decode("utf-8")


def is_hangul(cp):
    return S_BASE <= cp < S_BASE + S_COUNT


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen-normalize-tables.py UnicodeData.txt DerivedNormalizationProps.txt")
    data = read_checked(sys.argv[1], SHA256_DATA)
    props = read_checked(sys.argv[2], SHA256_PROPS)

    ccc = {}
    canon = {}   # direct canonical mapping
    compat = {}  # direct compatibility mapping (tagged)
    for line in data.splitlines():
        f = line.split(";")
        cp = int(f[0], 16)
        if int(f[3]):
            ccc[cp] = int(f[3])
        if f[5]:
            parts = f[5].split()
            if parts[0].startswith("<"):
                compat[cp] = [int(x, 16) for x in parts[1:]]
            else:
                canon[cp] = [int(x, 16) for x in parts]
    assert not any(is_hangul(cp) for cp in canon) and not any(is_hangul(cp) for cp in compat)

    qc_props = {}
    exclusions = set()
    for line in props.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        f = [x.strip() for x in line.split(";")]
        if "." in f[0]:
            lo, hi = [int(x, 16) for x in f[0].split("..")]
        else:
            lo = hi = int(f[0], 16)
        if f[1] == "Full_Composition_Exclusion":
            exclusions.update(range(lo, hi + 1))
        elif f[1] in ("NFD_QC", "NFC_QC", "NFKD_QC", "NFKC_QC"):
            flag = {("NFD_QC", "N"): NFD_NO, ("NFC_QC", "N"): NFC_NO, ("NFC_QC", "M"): NFC_MAYBE,
                    ("NFKD_QC", "N"): NFKD_NO, ("NFKC_QC", "N"): NFKC_NO,
                    ("NFKC_QC", "M"): NFKC_MAYBE}[(f[1], f[2])]
            for cp in range(lo, hi + 1):
                qc_props[cp] = qc_props.get(cp, 0) | flag
    assert len(exclusions) == 1120, len(exclusions)

    def full(cp, compatible):
        m = canon.get(cp)
        if m is None and compatible:
            m = compat.get(cp)
        if m is None:
            return [cp]
        result = []
        for c in m:
            result.extend(full(c, compatible))
        return result

    keys = sorted(set(canon) | set(compat))
    pool = []
    pool_index = {}

    def place(seq):
        key = tuple(seq)
        if key not in pool_index:
            pool_index[key] = len(pool)
            pool.extend(seq)
        return pool_index[key]

    canon_start, canon_len, compat_start, compat_len = [], [], [], []
    for cp in keys:
        if cp in canon:
            seq = full(cp, False)
            canon_start.append(place(seq))
            canon_len.append(len(seq))
        else:
            canon_start.append(0)
            canon_len.append(0)
        seq = full(cp, True)
        compat_start.append(place(seq))
        compat_len.append(len(seq))
    assert max(compat_len) <= 255

    pairs = sorted((m[0], m[1], cp) for cp, m in canon.items()
                   if len(m) == 2 and cp not in exclusions)
    assert all(ccc.get(p[0], 0) == 0 for p in pairs)
    assert all(not is_hangul(p[2]) for p in pairs)

    # recompute the quick check properties from the tables
    seconds = set(p[1] for p in pairs) | set(range(V_BASE, V_BASE + V_COUNT)) | \
        set(range(T_BASE + 1, T_BASE + T_COUNT))
    computed = {}
    for cp in range(0x110000):
        flags = 0
        if cp in canon or is_hangul(cp):
            flags |= NFD_NO
        if cp in canon or cp in compat or is_hangul(cp):
            flags |= NFKD_NO
        if cp in exclusions:
            flags |= NFC_NO
        if cp in exclusions or full(cp, True) != full(cp, False):
            flags |= NFKC_NO
        if cp in seconds:
            flags |= NFC_MAYBE
            if not flags & NFKC_NO:
                flags |= NFKC_MAYBE
        if flags:
            computed[cp] = flags
    for cp in set(computed) | set(qc_props):
        if computed.get(cp, 0) != qc_props.get(cp, 0):
            sys.exit("quick check of U+%04X: computed %d, file %d" % (cp, computed.get(cp, 0), qc_props.get(cp, 0)))

    def ranges(values):
        result = []
        start = None
        for cp in range(0x110001):
            v = values.get(cp, 0) if cp < 0x110000 else 0
            if start is not None and v != result_value:
                result.append((start, cp - 1, result_value))
                start = None
            if start is None and v:
                start, result_value = cp, v
        return result

    ccc_ranges = ranges(ccc)
    qc_ranges = ranges(qc_props)

    lines = [HEADER, "const"]

    def array(name, count_name, kind, values, per_line, hexa):
        lines.append("  %s: array[0..%s - 1] of %s = (" % (name, count_name, kind))
        texts = [("$%X" % v) if hexa else str(v) for v in values]
        for i in range(0, len(texts), per_line):
            lines.append("    " + ", ".join(texts[i:i + per_line]) + ("," if i + per_line < len(texts) else ""))
        lines.append("  );")

    lines.append("  NormDecompCount = %d;" % len(keys))
    lines.append("  NormPoolCount = %d;" % len(pool))
    lines.append("  NormCccCount = %d;" % len(ccc_ranges))
    lines.append("  NormPairCount = %d;" % len(pairs))
    lines.append("  NormQcCount = %d;" % len(qc_ranges))
    lines.append("  { decomposable code points; full canonical mapping (length 0: none)")
    lines.append("    and full compatibility mapping, as Start/Len in NormPool }")
    array("NormDecompKey", "NormDecompCount", "Integer", keys, 10, True)
    array("NormCanonStart", "NormDecompCount", "Integer", canon_start, 12, False)
    array("NormCanonLen", "NormDecompCount", "Byte", canon_len, 25, False)
    array("NormCompatStart", "NormDecompCount", "Integer", compat_start, 12, False)
    array("NormCompatLen", "NormDecompCount", "Byte", compat_len, 25, False)
    array("NormPool", "NormPoolCount", "Integer", pool, 10, True)
    lines.append("  { canonical combining classes other than 0 }")
    array("NormCccLo", "NormCccCount", "Integer", [r[0] for r in ccc_ranges], 10, True)
    array("NormCccHi", "NormCccCount", "Integer", [r[1] for r in ccc_ranges], 10, True)
    array("NormCccValue", "NormCccCount", "Byte", [r[2] for r in ccc_ranges], 25, False)
    lines.append("  { primary composites, sorted by first and second code point }")
    array("NormPairFirst", "NormPairCount", "Integer", [p[0] for p in pairs], 10, True)
    array("NormPairSecond", "NormPairCount", "Integer", [p[1] for p in pairs], 10, True)
    array("NormPairComposite", "NormPairCount", "Integer", [p[2] for p in pairs], 10, True)
    lines.append("  { quick check flags other than 0 (NormQc* in LandrixXmlNormalize.pas) }")
    array("NormQcLo", "NormQcCount", "Integer", [r[0] for r in qc_ranges], 10, True)
    array("NormQcHi", "NormQcCount", "Integer", [r[1] for r in qc_ranges], 10, True)
    array("NormQcFlags", "NormQcCount", "Byte", [r[2] for r in qc_ranges], 25, False)
    with open(OUT, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d decompositions, %d pool entries, %d ccc ranges, %d pairs, %d quick check ranges written to %s"
          % (len(keys), len(pool), len(ccc_ranges), len(pairs), len(qc_ranges), OUT))


if __name__ == "__main__":
    main()
