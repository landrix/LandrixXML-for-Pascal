#!/usr/bin/env python3
"""Generate source/LandrixXmlUnicodeData.inc from UnicodeData.txt 6.2.0.

The general categories are taken from Unicode 6.2.0 because Saxon HE 12,
the engine of the KoSIT validator, uses exactly that version for regular
expressions (\\d, \\w, \\p{..}); checked code point by code point against
Saxon's own category table. The file is downloaded once into a folder of
your choice and verified by its SHA-256:

  curl -o UnicodeData.txt https://www.unicode.org/Public/6.2.0/ucd/UnicodeData.txt
  python tools/gen-unicode-tables.py UnicodeData.txt

Output: consecutive code points with the same category are merged into
ranges; code points that are not listed are unassigned (Cn). Surrogates
(Cs) are kept although UTF-8 text never contains them.

The generated file is committed; rerun this script only to change the
format.
"""

import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "source", "LandrixXmlUnicodeData.inc")
SHA256 = "8b2cd18247527aa08ec320c3352b6a01b95d63199f20b3b593ea5d5217bdd170"

# Order defines the ordinal values of TLandrixXmlUnicodeCategory.
CATEGORIES = ["Cn", "Cc", "Cf", "Co", "Cs", "Ll", "Lm", "Lo", "Lt", "Lu", "Mc", "Me", "Mn",
              "Nd", "Nl", "No", "Pc", "Pd", "Pe", "Pf", "Pi", "Po", "Ps", "Sc", "Sk", "Sm",
              "So", "Zl", "Zp", "Zs"]

HEADER = """{ LandrixXml - dependency-free XML library for Delphi and Free Pascal.

  Copyright (c) 2026 Landrix Software
  Licensed under the MIT License. See the LICENSE file in the project root
  or https://opensource.org/licenses/MIT for the full license text.

  GENERATED by tools/gen-unicode-tables.py - do not edit.

  Unicode general categories, version 6.2.0, as ranges sorted by code
  point. Code points not covered are unassigned (Cn). Derived from
  UnicodeData.txt, Copyright (c) 1991-2012 Unicode, Inc., distributed
  under the Unicode terms of use (https://www.unicode.org/copyright.html). }
"""


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit("unexpected SHA-256 %s (expected UnicodeData.txt 6.2.0)" % digest)
    cats = ["Cn"] * 0x110000
    first = None
    for line in data.decode("ascii").splitlines():
        fields = line.split(";")
        cp, name, cat = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cp
            continue
        if name.endswith(", Last>"):
            for c in range(first, cp + 1):
                cats[c] = cat
            continue
        cats[cp] = cat
    ranges = []
    start = 0
    for c in range(1, 0x110001):
        if c == 0x110000 or cats[c] != cats[start]:
            if cats[start] != "Cn":
                ranges.append((start, c - 1, CATEGORIES.index(cats[start])))
            start = c
    lines = [HEADER]
    lines.append("const")
    lines.append("  UnicodeRangeCount = %d;" % len(ranges))
    for name, idx in (("UnicodeRangeLo", 0), ("UnicodeRangeHi", 1)):
        lines.append("  %s: array[0..UnicodeRangeCount - 1] of Integer = (" % name)
        values = ["$%X" % r[idx] for r in ranges]
        for i in range(0, len(values), 10):
            chunk = ", ".join(values[i:i + 10])
            lines.append("    " + chunk + ("," if i + 10 < len(values) else ""))
        lines.append("  );")
    lines.append("  UnicodeRangeCategory: array[0..UnicodeRangeCount - 1] of Byte = (")
    values = [str(r[2]) for r in ranges]
    for i in range(0, len(values), 25):
        chunk = ", ".join(values[i:i + 25])
        lines.append("    " + chunk + ("," if i + 25 < len(values) else ""))
    lines.append("  );")
    with open(OUT, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d ranges written to %s" % (len(ranges), OUT))


if __name__ == "__main__":
    main()
