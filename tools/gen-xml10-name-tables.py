#!/usr/bin/env python3
"""Generate source/LandrixXmlNameData4.inc: the character classes of
XML 1.0 Fourth Edition, Appendix B (BaseChar, Ideographic, CombiningChar,
Digit, Extender), which define Letter, NameChar and Name there.

The XML Schema validator of the Java runtime (Xerces, used by the KoSIT
validator) checks the built-in types Name, NCName, ID, IDREF and NMTOKEN
with these classes, not with the simpler ones of the Fifth Edition that
the parser uses. The specification is downloaded once and verified by its
SHA-256:

  curl -o REC-xml-20060816.html https://www.w3.org/TR/2006/REC-xml-20060816/
  python tools/gen-xml10-name-tables.py REC-xml-20060816.html

The generated file is committed; rerun this script only to change the
format.
"""

import hashlib
import html
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "source", "LandrixXmlNameData4.inc")
SHA256 = "a520bc8c34a6ae9a6b9f80440f0edc5d017c8562f6ec259d3888f2a2a3520021"

HEADER = """{ LandrixXml - dependency-free XML library for Delphi and Free Pascal.

  Copyright (c) 2026 Landrix Software
  Licensed under the MIT License. See the LICENSE file in the project root
  or https://opensource.org/licenses/MIT for the full license text.

  GENERATED by tools/gen-xml10-name-tables.py - do not edit.

  Character classes of Extensible Markup Language (XML) 1.0 (Fourth
  Edition), W3C Recommendation 16 August 2006, Appendix B, as sorted
  code point ranges:
    Letter    = BaseChar | Ideographic
    NameChar4 = Letter | Digit | '.' | '-' | '_' | ':' | CombiningChar | Extender }
"""


def production(text, name):
    start = text.index('id="NT-%s"' % name)
    # up to the next production, or the end of the table for the last one
    ends = [i for i in (text.find('id="NT-', start + 10), text.find("</table>", start)) if i >= 0]
    end = min(ends)
    chunk = html.unescape(re.sub(r"<[^>]+>", "", text[start:end]))
    chunk = chunk[chunk.index("::="):]
    ranges = []
    for lo, hi in re.findall(r"#x([0-9A-Fa-f]+)(?:-#x([0-9A-Fa-f]+))?", chunk):
        ranges.append((int(lo, 16), int(hi or lo, 16)))
    return ranges


def merge(ranges):
    ranges = sorted(ranges)
    out = []
    for lo, hi in ranges:
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(out[-1][1], hi))
        else:
            out.append((lo, hi))
    return out


def emit(lines, name, ranges):
    lines.append("  %sCount = %d;" % (name, len(ranges)))
    lines.append("  %sRanges: array[0..%sCount * 2 - 1] of Integer = (" % (name, name))
    values = []
    for lo, hi in ranges:
        values += ["$%X" % lo, "$%X" % hi]
    for i in range(0, len(values), 10):
        lines.append("    " + ", ".join(values[i:i + 10]) + ("," if i + 10 < len(values) else ""))
    lines.append("  );")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit("unexpected SHA-256 %s (expected the XML 1.0 Fourth Edition)" % digest)
    text = data.decode("utf-8", errors="replace")
    base = production(text, "BaseChar")
    ideo = production(text, "Ideographic")
    comb = production(text, "CombiningChar")
    digit = production(text, "Digit")
    ext = production(text, "Extender")
    assert (base[0], len(base)) == ((0x41, 0x5A), 202), (base[0], len(base))
    assert ideo == [(0x4E00, 0x9FA5), (0x3007, 0x3007), (0x3021, 0x3029)], ideo
    assert (comb[0], digit[0], ext[0]) == ((0x300, 0x345), (0x30, 0x39), (0xB7, 0xB7))
    letter = merge(base + ideo)
    name_char = merge(letter + digit + comb + ext + [(0x2E, 0x2E), (0x2D, 0x2D), (0x5F, 0x5F), (0x3A, 0x3A)])
    lines = [HEADER, "const"]
    emit(lines, "XmlLetter4", letter)
    emit(lines, "XmlNameChar4", name_char)
    with open(OUT, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d letter and %d name character ranges written to %s" % (len(letter), len(name_char), OUT))


if __name__ == "__main__":
    main()
